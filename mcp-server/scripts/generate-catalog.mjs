#!/usr/bin/env node
/**
 * Codegen script — generates ACTION_CATALOG files and tool manifest from MCP tool definitions.
 *
 * The MCP tool definitions in src/tools/*.ts are the single source of truth.
 * This script derives:
 *   1. runtime/src/actionCatalog.generated.ts   (TypeScript ACTION_CATALOG entries)
 *   2. runtime-py/nookplot_runtime/action_catalog_generated.py (Python equivalent)
 *   3. cli/src/tool-manifest.json               (JSON manifest for skill doc generation)
 *   4. Tool count updates in static files        (SKILL.md, README.md)
 *
 * Usage: cd mcp-server && npm run build && npm run generate-catalog
 */

import { ALL_TOOLS, TOOL_COUNT, ALL_CATEGORIES } from "../dist/tools/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "../..");

// ── Helpers ──

function extractParams(schema) {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  return Object.entries(props)
    .map(([k, v]) => {
      const type = v.type || "any";
      const opt = required.has(k) ? "" : ", optional";
      return `${k} (${type}${opt})`;
    })
    .join(", ");
}

function escapeStr(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
}

// ── 1. Generate tool manifest JSON ──

const manifest = ALL_TOOLS.map((t) => ({
  name: t.name,
  actionName: t.name.replace(/^nookplot_/, ""),
  description: t.description,
  category: t.category,
  params: extractParams(t.inputSchema),
  required: t.inputSchema.required ?? [],
}));

writeFileSync(
  join(ROOT, "cli/src/tool-manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(`  cli/src/tool-manifest.json — ${manifest.length} tools`);

// ── 2. Generate TypeScript ACTION_CATALOG ──

const tsEntries = manifest
  .map((t) => {
    const lines = [`  ${t.actionName}: {`];
    lines.push(`    description: "${escapeStr(t.description)}",`);
    if (t.params) {
      lines.push(`    params: "${escapeStr(t.params)}",`);
    }
    lines.push(`    category: "${t.category}",`);
    lines.push("  },");
    return lines.join("\n");
  })
  .join("\n");

const tsContent = `// AUTO-GENERATED by mcp-server/scripts/generate-catalog.ts
// DO NOT EDIT — run \`npm run generate-catalog\` in mcp-server to regenerate.

import type { ActionInfo } from "./actionCatalog.js";

/** MCP-derived action catalog entries (${manifest.length} tools). */
export const GENERATED_CATALOG: Record<string, ActionInfo> = {
${tsEntries}
};
`;

writeFileSync(join(ROOT, "runtime/src/actionCatalog.generated.ts"), tsContent);
console.log(`  runtime/src/actionCatalog.generated.ts — ${manifest.length} entries`);

// ── 3. Generate Python ACTION_CATALOG ──

const pyEntries = manifest
  .map((t) => {
    const lines = [`    "${t.actionName}": {`];
    lines.push(`        "description": "${escapeStr(t.description)}",`);
    if (t.params) {
      lines.push(`        "params": "${escapeStr(t.params)}",`);
    }
    lines.push(`        "category": "${t.category}",`);
    lines.push("    },");
    return lines.join("\n");
  })
  .join("\n");

const pyContent = `# AUTO-GENERATED by mcp-server/scripts/generate-catalog.ts
# DO NOT EDIT — run \`npm run generate-catalog\` in mcp-server to regenerate.

from __future__ import annotations

from typing import TypedDict


class ActionInfo(TypedDict, total=False):
    description: str
    params: str


GENERATED_CATALOG: dict[str, ActionInfo] = {
${pyEntries}
}
`;

writeFileSync(
  join(ROOT, "runtime-py/nookplot_runtime/action_catalog_generated.py"),
  pyContent,
);
console.log(`  runtime-py/.../action_catalog_generated.py — ${manifest.length} entries`);

// ── 4. Update tool counts in static files ──

const countFiles = [
  "mcp-server/SKILL.md",
  "mcp-server/README.md",
];

let updatedCount = 0;
for (const relPath of countFiles) {
  const filePath = join(ROOT, relPath);
  try {
    const content = readFileSync(filePath, "utf-8");
    const updated = content.replace(/\b\d+ (MCP )?tools\b/g, (_match, prefix) => {
      return `${TOOL_COUNT} ${prefix ?? ""}tools`;
    });
    if (updated !== content) {
      writeFileSync(filePath, updated);
      updatedCount++;
      console.log(`  ${relPath} — updated tool count to ${TOOL_COUNT}`);
    }
  } catch {
    // File may not exist in all environments
  }
}


console.log(
  `\nDone. Generated ${manifest.length} tools, updated ${updatedCount} files.`,
);
